const {test} = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
test('text size defaults large, persists independently, and syncs across pages', () => {
  const events = {}, handlers = {}, changes = {};
  const root = {dataset:{}};
  const control = {addEventListener:(event, fn) => changes[event] = fn};
  const stored = new Map();
  const window = {localStorage:{getItem:k => stored.get(k), setItem:(k,v) => stored.set(k,v)},addEventListener:(event,fn) => events[event] = fn};
  const document = {documentElement:root,querySelectorAll:() => [control],querySelector:() => null,addEventListener:(event,fn) => handlers[event] = fn};
  const source = fs.readFileSync(require.resolve('../dist/text-size.js'),'utf8');
  vm.runInNewContext(source,{window,document});
  assert.equal(root.dataset.textSize,'large');
  handlers.DOMContentLoaded();
  control.value = 'extra'; changes.change();
  assert.equal(root.dataset.textSize,'extra');
  assert.equal(stored.get('yeumap-text-size-v1'),'extra');
  root.dataset.textSize = '';
  vm.runInNewContext(source,{window,document});
  assert.equal(root.dataset.textSize,'extra');
  events.storage({key:'yeumap-theme-v1',newValue:'dark'});
  assert.equal(root.dataset.textSize,'extra');
  events.storage({key:'yeumap-text-size-v1',newValue:'normal'});
  assert.equal(root.dataset.textSize,'normal');
  events.storage({key:null,newValue:null});
  assert.equal(root.dataset.textSize,'large');
  window.localStorage.getItem = () => {throw Error('denied');};
  window.localStorage.setItem = () => {throw Error('denied');};
  assert.doesNotThrow(() => vm.runInNewContext(source,{window,document}));
  handlers.DOMContentLoaded(); control.value='extra'; changes.change();
  assert.equal(root.dataset.textSize,'extra');
});
